-- 2026_11_28_70_world_everlake_missing_creature_gold.sql: written by hand, not tried in game (2026-11-28).
--
-- The core drops a creature's money only from its difficulty row's GoldMin / GoldMax (Unit::... generateMoneyLoot).
-- 6,696 of the 9,707 spawned creatures have both at 0; 326 of them drop money on live (Wowhead Forever's "Worth", the
-- average money per kill, or Icy Veins' recorded average coin from players' loot windows).
-- Range: measured on the realm's own creatures that have gold and a live figure (420 with Wowhead's Worth, 357 with Icy
-- Veins'): the realm's average gold matches Wowhead's Worth (median ratio 0.996), with GoldMin 0.345x and GoldMax 1.598x
-- of it; against Icy Veins the realm runs 1.158x, GoldMin 0.444x and GoldMax 1.933x. So GoldMin / GoldMax here are those
-- medians times Wowhead's Worth, else times Icy Veins' average coin.
-- Left out: 115 beasts whose only figure is Wowhead's Worth. Classic beasts rarely drop coin (71 of the realm's 1,171
-- do) and Icy Veins' live records show none for them; the 5 beasts Icy Veins records dropping coin are in.
-- Rows change only while GoldMin and GoldMax are both 0. Every change is recorded in everlake_import_rows.
-- Never edit this file once it is deployed: a later fix is a new file. Running it again changes nothing.

