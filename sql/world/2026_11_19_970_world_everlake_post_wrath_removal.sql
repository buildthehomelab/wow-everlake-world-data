-- Content after Wrath of the Lich King: removed from the world. TBC and Wrath rows stay.
-- 2026_11_19_970_world_everlake_post_wrath_removal.sql: written by hand; the id ranges below were computed on a world
-- built the way CI builds the PTR's (the Forever TDB, the core's world files, every file here up to 966).
--
-- The world came from a retail-era TDB dump, so it holds templates, quests and menus from every expansion. The
-- client's Map.db2 has only the Classic maps and Forever's own, so none of the later content can be reached. Rule:
--   - A creature or gameobject template is cut when it is not in AzerothCore's 3.3.5 world (azerothcore-wotlk
--     data/sql/base/db_world, the Wrath-and-earlier list), not spawned, not added by an Everlake file
--     (everlake_import_rows), not summoned or transformed into by a client or serverside spell, not named in the
--     core's Custom scripts, and not used by anything that stays (see below).
--   - A quest is cut when it is not in AzerothCore's 3.3.5 world, not in the client's QuestV2.db2, not started by a
--     client item, not added by an Everlake file, not given or taken by a spawned creature or gameobject, not tagged
--     TBC or Wrath (Expansion 1-2), not named in the core's Custom scripts, and not used by anything that stays.
--   - "Used by anything that stays", worked out until nothing changed: objectives and prerequisites (PrevQuestID,
--     NextQuestID, breadcrumbs) of kept quests, kill credits and vehicle accessories of kept creatures, summon
--     groups and SmartAI of kept owners (summons, kill credits, targets, quest actions, actionlists they call),
--     conditions whose own source stays, spell_area rows of client spells, areatrigger quests.
--   - A gossip menu is cut when only cut creatures show it and no menu that stays leads to it; a trainer when only
--     cut creatures use it; loot when only cut creatures or gameobjects use it.
--   - Maps after Wrath: map ids from 643 up that are neither Wrath maps nor in the client (437 maps, all below
--     2700). Their instance, access, teleport, graveyard, spell position, areatrigger and spawn-tracking rows go.
--     Maps 2700 and up that the client lacks are left: Forever's own map ids live there too.
--   - Quests that stay no longer point at cut ones (RewardNextQuest, NextQuestID, PrevQuestID, breadcrumb set to 0).
-- On that world it removes 4.32 million rows: 197,995 creature templates, 63,541 gameobject templates, 36,815 quests,
-- 1,701 gossip menus, 24 trainers, 343 actionlists and the rows of 437 maps (counts per table: the pull request).
-- Rows kept although they are not Wrath or Forever, and why: docs/audits/2026-11-19-post-wrath-kept.csv.
-- Everything else that names a cut row (SmartAI, conditions, texts, locales, models, quest starters and enders,
-- objectives, POIs, vendors, spellclicks, equipment, classic level and stat rows) goes with it.
--
-- Not checked in game. Never edit this file once it is deployed: a later fix is a new file. Running it again changes
-- nothing.


