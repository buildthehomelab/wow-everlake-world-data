FROM `everlake_pp_ok` o WHERE o.`setid` = 1;
UPDATE `creature_template_difficulty` d JOIN `everlake_pp_ok` o ON o.`entry` = d.`Entry`
SET d.`PickPocketLootID` = o.`tid` WHERE d.`DifficultyID` = 0 AND o.`setid` = 1;
