-- the table id: PickPocketLootID when set and unshared, else the entry when free; only while it has no rows
DROP TEMPORARY TABLE IF EXISTS `everlake_pp_ok`;
CREATE TEMPORARY TABLE `everlake_pp_ok` (`entry` INT UNSIGNED NOT NULL PRIMARY KEY, `tid` INT UNSIGNED NOT NULL, `setid` TINYINT NOT NULL);
INSERT INTO `everlake_pp_ok` (`entry`, `tid`, `setid`)
SELECT d.`Entry`, IF(d.`PickPocketLootID` > 0, d.`PickPocketLootID`, d.`Entry`), IF(d.`PickPocketLootID` > 0, 0, 1)
FROM `creature_template_difficulty` d
WHERE d.`DifficultyID` = 0 AND d.`Entry` IN (SELECT DISTINCT p.`entry` FROM `everlake_pp` p)
  AND NOT EXISTS (SELECT 1 FROM `pickpocketing_loot_template` l WHERE l.`Entry` = IF(d.`PickPocketLootID` > 0, d.`PickPocketLootID`, d.`Entry`))
  AND NOT EXISTS (SELECT 1 FROM `creature_template_difficulty` d2 WHERE d2.`PickPocketLootID` = IF(d.`PickPocketLootID` > 0, d.`PickPocketLootID`, d.`Entry`)
                    AND d2.`Entry` <> d.`Entry`);

INSERT INTO `pickpocketing_loot_template` (`Entry`, `ItemType`, `Item`, `Chance`, `QuestRequired`, `LootMode`, `GroupId`, `MinCount`, `MaxCount`, `Comment`)
SELECT o.`tid`, 0, p.`item`, p.`chance`, 0, 1, 0, p.`mn`, p.`mx`, LEFT(p.`note`, 100)
FROM `everlake_pp` p JOIN `everlake_pp_ok` o ON o.`entry` = p.`entry`;
INSERT IGNORE INTO `everlake_import_rows` (`tbl`, `k1`, `k2`, `k3`, `k4`, `file`, `note`)
SELECT 'pickpocketing_loot_template', o.`tid`, 0, p.`item`, 0, @EVERLAKE_FILE, CONCAT(p.`note`, ' (creature ', p.`entry`, ')')
FROM `everlake_pp` p JOIN `everlake_pp_ok` o ON o.`entry` = p.`entry`;
INSERT IGNORE INTO `everlake_import_rows` (`tbl`, `k1`, `k2`, `k3`, `k4`, `file`, `note`)
