-- that rightly drop nothing) against Wowhead Forever's drop tabs (kills and drop counts), Icy Veins' recorded loot and
-- EG Link's loot record. Critters' "drops" there are skinning (Icy Veins spell 8613), not corpse loot, and are left out.
-- 11 creatures drop corpse loot on live with a real kill sample:
--   a) Nethergarde Soldier 5999 (56 spawns; Wowhead 745 kills, Mageweave Cloth in 73%), Nethergarde Elite 7851 (14) and
--      Nethergarde Officer 6003 (5) HAVE their Classic loot tables (38, 20 and 18 rows, entry = creature id) but their
--      difficulty row's LootID is 0, so the core never uses them. LootID set to the table.
--   b) No table at all; one is built from Wowhead Forever's kill counts (chance = drops / kills, stack sizes as Wowhead
--      shows; items seen only once left out as noise; quest items QuestRequired). LootID = the creature id (free).
--      Mindless Gorger 268300 and Saltscale Muckdweller 258849 (The Drowned City; 1,289 and 966 kills, world drops; plus
--      the dungeon's Craftsman's Writ reference 9500002 at 0.5 as its other mobs have), Brashann Grimdark 260440 (285),
--      Ur'dan 14522 (129), Mazzogore 252457 (72), Bethra'zel 263394 (39).
--   Left out: Dope'rel 9040 (Blackrock Depths' Seven) and Thane Korth'azz 16064 (Four Horsemen) loot from their shared
--   chests; Cavalry Guard 257080 (13 kills, one drop each: too thin).
-- Rows only go in while the creature still has LootID 0 and the table id is free. Every added row is recorded in
-- everlake_import_rows. Never edit this file once it is deployed: a later fix is a new file. Running it again changes nothing.

CREATE TABLE IF NOT EXISTS `everlake_import_rows` (
  `tbl` varchar(64) NOT NULL COMMENT 'world table of the row',
  `k1` bigint NOT NULL COMMENT 'the row''s key, in the table''s primary key order',
  `k2` bigint NOT NULL DEFAULT '0',
  `k3` bigint NOT NULL DEFAULT '0',
  `k4` bigint NOT NULL DEFAULT '0',
  `file` varchar(200) NOT NULL COMMENT 'the update file that added the row',
  `note` varchar(255) NOT NULL DEFAULT '' COMMENT 'the sources that gave it',
  PRIMARY KEY (`tbl`, `k1`, `k2`, `k3`, `k4`),
  KEY `file` (`file`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Rows the Everlake world import added';
